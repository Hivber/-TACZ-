#[derive(Clone, Debug)]
pub struct LocalBlockCatalog {
    by_identifier: HashMap<&'static str, i32>,
}

impl LocalBlockCatalog {
    pub fn new() -> Result<Self, String> {
        let mut by_identifier = HashMap::with_capacity(VANILLA_BLOCK_IDENTIFIERS.len());
        for (index, identifier) in VANILLA_BLOCK_IDENTIFIERS.iter().copied().enumerate() {
            if by_identifier.insert(identifier, index as i32).is_some() {
                return Err(format!("duplicate vanilla block identifier {identifier:?}"));
            }
        }
        Ok(Self { by_identifier })
    }

    pub fn id(&self, identifier: &str) -> Option<i32> {
        self.by_identifier.get(identifier).copied()
    }

    pub fn identifier(&self, local_id: i32) -> Option<&'static str> {
        if local_id < 0 { return None; }
        VANILLA_BLOCK_IDENTIFIERS.get(local_id as usize).copied()
    }

    pub fn len(&self) -> usize { VANILLA_BLOCK_IDENTIFIERS.len() }
    pub fn is_empty(&self) -> bool { VANILLA_BLOCK_IDENTIFIERS.is_empty() }
}

impl Default for LocalBlockCatalog {
    fn default() -> Self { Self::new().expect("vanilla block identifier table must be unique") }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn full_vanilla_id_catalog_round_trips_without_wire_id_assumptions() {
        let catalog = LocalBlockCatalog::new().unwrap();
        assert_eq!(catalog.len(), 1492);
        for identifier in VANILLA_BLOCK_IDENTIFIERS {
            let id = catalog.id(identifier).unwrap();
            assert_eq!(catalog.identifier(id), Some(*identifier));
        }
        let air_id = catalog.id(block_id::AIR).unwrap();
        assert_eq!(catalog.identifier(air_id), Some(block_id::AIR));
        assert_eq!(catalog.identifier(-1), None);
    }

    #[test]
    fn unknown_identifiers_are_not_silently_converted() {
        let catalog = LocalBlockCatalog::default();
        assert_eq!(catalog.id("minecraft:not_a_vanilla_block"), None);
    }
}
